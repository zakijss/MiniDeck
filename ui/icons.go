// tile draws an icon on a bevelled colour tile (ink outline, light top left,
// dark bottom right, hard shadow), like a small app icon.
func (s *Screen) tile(name string, r image.Rectangle, c ramp) {
	sh := rectShape(r, 8)
	s.dropShadow(sh, 1, 110)
	s.bevel(sh, c, Ink)
	fg := Ink
	if !light(c.base) {
		fg = whiteRamp.hi
	}
	sz := min(r.Dx(), r.Dy())
	k := iconScale(sz * 3 / 5)
	gx := r.Min.X + (r.Dx()-12*k)/2
	gy := r.Min.Y + (r.Dy()-12*k)/2
	if g, ok := glyphs[name]; ok {
		if fg == Ink { // a light shadow under ink glyphs, a dark one under white
			s.bitmap(gx+k, gy+k, k, g, c.hi, nil)
		} else {
			s.bitmap(gx+k, gy+k, k, g, c.lo, nil)
		}
		s.bitmap(gx, gy, k, g, fg, nil)
	}
}
